"""Numpy reference for the syncer's Delayed Nesterov outer optimizer.

Delayed Nesterov: the outer gradient is applied every step; the momentum is
updated only every N outer steps, with the mean of those N gradients. This test pins the
values that ``syncer/src/merge.rs::delayed_nesterov_matches_numpy_reference``
hard-codes. Run this file directly to print fresh values for that Rust test.
"""

from __future__ import annotations

import pytest

np = pytest.importorskip("numpy")

LR = np.float32(0.7)
MU = np.float32(0.9)
PERIOD = 3
THETA0 = (1.0, -2.0)
DELTAS = (
    (0.5, -0.25),
    (0.125, 0.75),
    (-0.375, 0.5),
    (1.0, -1.0),
    (0.25, 0.0625),
    (-0.5, 0.875),
    (0.75, -0.125),
)
# Generated by ``python tests/test_delayed_nesterov_reference.py``.
EXPECTED_PARAMS = (0.3344166874885559, -2.575458288192749)
EXPECTED_MOMENTUM = (0.32499998807907104, 0.27916666865348816)
EXPECTED_ACCUM = (0.75, -0.125)


def delayed_nesterov(theta, deltas, *, lr, mu, period):
    """θ moves every step, m only every N steps."""
    n = np.float32(period)
    theta = np.asarray(theta, dtype=np.float32).copy()
    momentum = np.zeros_like(theta)
    accum = np.zeros_like(theta)
    for t, delta in enumerate(deltas):
        g = np.asarray(delta, dtype=np.float32)
        accum = accum + g
        if (t + 1) % period == 0:
            momentum = mu * momentum + accum / n
            theta = theta - lr * (mu * momentum + g / n)
            accum = np.zeros_like(theta)
        else:
            theta = theta - lr * (g / n)
    return theta, momentum, accum


def nesterov(theta, deltas, *, lr, mu):
    theta = np.asarray(theta, dtype=np.float32).copy()
    momentum = np.zeros_like(theta)
    for delta in deltas:
        g = np.asarray(delta, dtype=np.float32)
        momentum = mu * momentum + g
        theta = theta - lr * (g + mu * momentum)
    return theta, momentum


def test_reference_matches_rust_constants():
    theta, momentum, accum = delayed_nesterov(THETA0, DELTAS, lr=LR, mu=MU, period=PERIOD)
    np.testing.assert_allclose(theta, EXPECTED_PARAMS, rtol=0, atol=1e-6)
    np.testing.assert_allclose(momentum, EXPECTED_MOMENTUM, rtol=0, atol=1e-6)
    np.testing.assert_allclose(accum, EXPECTED_ACCUM, rtol=0, atol=1e-6)


def test_period_one_is_nesterov():
    dn_theta, dn_momentum, _ = delayed_nesterov(THETA0, DELTAS, lr=LR, mu=MU, period=1)
    theta, momentum = nesterov(THETA0, DELTAS, lr=LR, mu=MU)
    np.testing.assert_array_equal(dn_theta, theta)
    np.testing.assert_array_equal(dn_momentum, momentum)


if __name__ == "__main__":
    for name, values in zip(
        ("EXPECTED_PARAMS", "EXPECTED_MOMENTUM", "EXPECTED_ACCUM"),
        delayed_nesterov(THETA0, DELTAS, lr=LR, mu=MU, period=PERIOD),
    ):
        print(f"{name} = ({', '.join(repr(float(v)) for v in values)})")
