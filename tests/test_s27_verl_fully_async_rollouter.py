GROUPS, SAMPLES = 2, 2


class RolloutActor(FullBufferActor):
    """``FullBufferActor`` plus verl's rollouter behind the trainer actor's queue calls."""

    def __init__(self, seed: int = 0):
        super().__init__(seed=seed)
        self.pushed: list[tuple[int, dict[str, torch.Tensor]]] = []  # (param version, rollouter weights)
        self.started = 0
        self.uids = 0
        self.queued_old: list[int] = []  # param versions of groups generated before the last push
        self.last = None

    def start(self):
        self.started += 1

    def yeto_push_weights(self):
        if self.pushed:  # a group the rollouter generated with the previous weights is still queued
            self.queued_old.append(self.pushed[-1][0])
        self.pushed.append((self.param_version, self.model.values()))
        return {"param_version": self.param_version, "timing": {"update_weights_s": 0.01}}

    def yeto_pull_sample(self):
        assert self.started == 1, "the rollouter generates only after the first publication"
        version = self.queued_old.pop(0) if self.queued_old else self.pushed[-1][0]
        self.uids += 1
        self.last = {"uid": f"u{self.uids}", "min_steps": (version,) * SAMPLES, "max_steps": (version,) * SAMPLES,
                     "calls": (None,) * SAMPLES, "lengths": (4,) * SAMPLES, "rewards": (1.0, 0.0)}
        return self.last

    def yeto_keep_last(self):
        self.kept.append({"non_tensor": {"uid": [self.last["uid"]]}, "versions": self.last["min_steps"]})

    def yeto_drop_last(self):
        self.last = None


def test_a_full_parameter_fully_async_island_publishes_whole_weights_to_its_rollouter(tmp_path, verl_trainer):
    from yeto.rl.adapters.verl.separate import READBACK_STATUS

    rounds = 3
    actor = RolloutActor(seed=0)
    base = _full_base(tmp_path, actor.model)
    plan = _plan(tmp_path, base, rounds=rounds, groups=GROUPS)
    result = verl_trainer.run_fully_async_island(actor, actor.start, plan, {})
    assert result["rounds_completed"] == rounds and result["final_policy_version"] == rounds
    assert result["version_map"] == {str(v): v for v in range(rounds + 1)}
    # every publication pushed the trainer's weights at that version, in order
    assert [v for v, _w in actor.pushed] == list(range(rounds + 1))
    for version, weights in actor.pushed[1:]:
        for name, value in actor.trained[version].items():
            assert torch.equal(weights[name], value)
    records = _lines(tmp_path / "out" / "verl-publish-0.jsonl")
    assert [(r["policy_version"], r["param_version"], r["status"]) for r in records] == [
        (v, v, READBACK_STATUS) for v in range(rounds + 1)]
    # rounds train groups of their own version and of the previous one (the queued group)
    events = _lines(tmp_path / "tape.jsonl")
    groups = {e["rollout_id"]: [g[2] for g in e["groups"]] for e in events if e["event"] == "rl_group_policies"}
    assert set(groups) == set(range(rounds))
    for rollout_id, versions in groups.items():
        oldest = [min(v) if v else rollout_id for v in versions]
        assert all(rollout_id - 1 <= o <= rollout_id for o in oldest), (rollout_id, versions)
    assert any(min(v) == r - 1 for r, vs in groups.items() for v in vs if v), groups
    start = next(e for e in events if e["event"] == "rl_verl_island_start")
    assert start["parameter_mode"] == "full" and start["fully_async"] and start["max_policy_age"] == 1
    assert events[-1]["event"] == "rl_learner_finalized"
    assert actor.started == 1


def test_the_publication_refuses_a_state_the_trainer_moved_past(tmp_path, verl_trainer):
    from yeto.rl.adapters.verl import fully_async_full
    from yeto.rl.adapters.verl.fully_async_ports import FullyAsyncFullParameterPublisher, FullyAsyncIsland
    from yeto.rl.engine.policy_digest import WeightsChanged

    actor = RolloutActor(seed=0)
    base = _full_base(tmp_path, actor.model)
    plan = _plan(tmp_path, base, rounds=1, groups=1)
    layout_hash, identity = fully_async_full.full_parameter_hashes(plan)
    island = FullyAsyncIsland(actor, learner_id=0, limit=1, required=1, out_dir=str(tmp_path / "out"),
                              readback_dir=str(tmp_path / "rb"), base_model_revision=plan["model_revision"],
                              lora_config_hash=identity, layout_hash=layout_hash)
    _sync, state = fully_async_full.full_parameter_ports(island, plan, backend_identity_sha256="c" * 64)
    exported = state.export(policy_version=0)
    island.full_group.trained_rounds += 1  # the trainer port recorded a round after the export
    with pytest.raises(WeightsChanged):
        FullyAsyncFullParameterPublisher(island).publish(exported)
    assert actor.pushed == []


def _island_args(**kw):
    values = dict(parameter_mode="full", rl_placement="fixed-partition", rl_island_gpus_per_node=None,
                  actor_num_gpus_per_node=1, actor_num_nodes=1, rollout_num_gpus=1, rollout_num_gpus_per_engine=1,
                  sglang_mem_fraction_static=0.7, lora_r=32, inner_lr=1e-6, groups_per_round=GROUPS,
                  samples_per_group=SAMPLES, rollout_max_response_len=64, seed=1, global_rounds=3,
                  reward_function="gsm8k_reward:score", learner_id=0, rl_max_policy_age=1, rl_rollout_ahead=0,
                  rl_sample_role=None)
    values.update(kw)
    return SimpleNamespace(**values)


def test_the_island_plans_the_fully_async_pools_without_the_separate_mode(tmp_path):
    args = _island_args()
    assert island_entry.rollout_ahead_of(args) == (0, 1)
    pools = island_entry.fsdp_separate_pools(args, {"after": {"GPU": 2.0}})
    run, overrides = island_entry.fsdp_island_run(
        args, model_path=str(tmp_path), train_file="/t", val_file="/v", out_dir=str(tmp_path / "o"),
        algo={"correction": "tis", "tis_upper": 2.0}, chat={}, ray_info={"after": {"GPU": 2.0}}, max_prompt=512,
        limit=1, pools=pools)
    assert run.lora_rank == 0 and run.parameter_mode == vconf.FULL_PARAMETER_MODE
    # not verl's separate mode (its trainer mode and pool keys); the fully_async keys come next
    assert f"trainer.v1.trainer_mode={separate.TRAINER_MODE}" not in overrides
    assert not [o for o in overrides if "separate_async" in o or o.startswith("actor_rollout_ref.rollout.nnodes=")]
    from test_s27_verl_sample_role import TOLERANT

    out, asserted = island_entry.fully_async_plan(1, overrides, TOLERANT.to_dict(), args, "none", pools=pools)
    assert "rollout.n_gpus_per_node=1" in out and "trainer.n_gpus_per_node=1" in out
    assert "actor_rollout_ref.hybrid_engine=False" in out and "rollout.n_gpus_per_node" in asserted
    # a 2 + 6 shape reaches the fully_async keys (a LoRA island keeps 1 + 1: pools=None)
    wide = separate.SeparatePools(1, 2, 1, 6, rollout_tp=1)
    out, _ = island_entry.fully_async_plan(1, overrides, TOLERANT.to_dict(), args, "none", pools=wide)
    assert "rollout.n_gpus_per_node=6" in out and "trainer.n_gpus_per_node=2" in out


