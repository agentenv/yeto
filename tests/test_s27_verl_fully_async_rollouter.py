"""S27 G-EV: a verl full-parameter fully_async island with its own rollouter (VERL-PARITY #11).

CPU only. The trainer runs ``trainer.run_fully_async_island`` itself with verl's
modules stubbed (G-EW's ``verl_trainer`` fixture); the trainer actor is G-EW's
``FullBufferActor`` (one FSDP2 actor worker behind the real worker functions)
plus the rollouter's queue: it serves the weights of its last push and keeps a
group generated by the previous push in its queue, as verl's rollouter does
while the trainer trains (policy age up to the limit). The driver, the
fully_async rollout port and collector, the full-parameter policy state
(``fully_async_full``) and the new publisher are the real ones. Checks:

* every publication pushes the trainer's weights at that version to the
  rollouter (no LoRA read-back; ``READBACK_NOT_IMPLEMENTED``) and records the
  param-version pairing; the rollouter starts after the first publication;
* rounds train groups generated up to one version back, never older;
* the island entry plans the fully_async path with the launcher's pool sizes and
  without verl's separate-mode keys, and refuses a colocated full-parameter
  fully_async island; the launcher accepts the fixed-partition launch.
"""
