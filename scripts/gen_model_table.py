#!/usr/bin/env python3
"""Regenerate docs/MODELS.md, the supported-models table, from yeto/models.py.

Usage: python3 scripts/gen_model_table.py   (rewrites docs/MODELS.md)
A test (tests/test_models.py) fails when the table drifts from the source.
"""

from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from yeto.models import MODEL_ALIASES, MODEL_WEIGHT_GB, TESTED_ALIASES  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parents[1] / "docs" / "MODELS.md"


def table(aliases) -> str:
    rows = ["| alias | Hugging Face id | min island VRAM (GB) |", "|---|---|---|"]
    for alias in aliases:
        hf = MODEL_ALIASES[alias]
        gb = MODEL_WEIGHT_GB.get(alias)
        size = f"{gb:g}" if gb is not None else "(Hub)"
        rows.append(f"| `{alias}` | `{hf}` | {size} |")
    return "\n".join(rows)


def render() -> str:
    return f"""# Supported models

`--model` takes any Hugging Face id or one of the aliases below, which are
sugar over `yeto/models.py`. This file is generated by
`scripts/gen_model_table.py`; `tests/test_models.py` keeps it in sync.

"Min island VRAM" is the frozen-base footprint an island's GPUs must jointly
hold (bf16 base, LoRA). Add about 8 GB per GPU for activations and overhead,
and multiply by 8 for full tuning. "(Hub)" means the size is resolved from
the SafeTensors metadata on the Hub at plan time.

## Tested

Aliases with a completed Yeto fine-tuning run on real hardware.

{table(a for a in MODEL_ALIASES if a in TESTED_ALIASES)}

## Other supported aliases

Supported by the alias table but not yet run end to end.

{table(a for a in MODEL_ALIASES if a not in TESTED_ALIASES)}

Diffusion aliases (`--model-kind diffusion`) are listed in
[DIFFUSION.md](DIFFUSION.md).
"""


def main() -> None:
    OUT.write_text(render())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
