"""Rollout ahead: the engines generate round r+1 while the trainer trains round r.

Why: a fixed-partition island runs its round serially (generate -> train ->
sync boundary -> publish), so the engine GPUs wait while the trainer works and
the trainer waits while the engines generate. s27-ba-a (2 islands, 8 trainer +
16 engine H200 each) spent 33% of a round generating, 20% training, 41% in the
sync boundary and 6% publishing, one after another.

What ``--rl-rollout-ahead 1`` changes in the driver's round (``IslandDriver``)::

    round r:  take batch r
              start batch r+1 on the engines (published policy v_r)
              train r -> sync boundary r (state v_{r+1})
              wait for batch r+1 -> publish v_{r+1} -> (eval)

* One whole batch at a time. The weight update (an NCCL write into the
  engines) never runs while the engines generate: the driver waits for the
  batch first and refuses a publication while one is in flight. The rollout
  side sees an ordinary on-policy batch of the policy it was given (no
  carry-over, no fully_async).
* Policy age: batch r+1 is generated by v_r and trained by v_{r+1}, so every
  sample lags exactly one version (round 0: none). The trainer's off-policy
  correction (TIS on the generation log-probabilities) covers the lag; the
  policy-age limit (``--rl-max-policy-age``) must be at least the lag.
* Engine weights after a DiLoCo boundary: the engines get the boundary's
  output state (the island's own step with every merged fragment already
  applied), the same state the trainer trains the next round from. It is the
  newest state that exists when the engines are free.
* Data position: the cursor recorded after boundary r is read before batch r+1
  draws its prompts, so a relaunched island draws batch r+1's rows again
  (they were never trained) and never skips them.
* The final round: a batch started before the stop is waited for (the final
  publication needs idle engines) and discarded; nothing trains it.
* A new process (Modal retry, relaunch, peer recovery) starts with nothing in
  flight: its first round generates serially from its start state.

Refused (fail closed, before launch and again when the driver starts):
colocated islands, sample-buffer roles, elastic reconfiguration, island round
cuts and the resume ledger, the overlapped evaluation, and rollout pools
without split generation (``start_generate`` / ``finish_generate``).
"""

from __future__ import annotations

from collections.abc import Iterable
from contextlib import ExitStack
from dataclasses import dataclass, field
from typing import Any

MAX_ROLLOUT_AHEAD = 1
FLAG = "--rl-rollout-ahead"
EVENT = "rl_rollout_ahead"


@dataclass
class PendingBatch:
    """The batch of ``rollout_id`` that the engines generate with the published
    policy ``policy_version`` while the trainer works.

    ``data_cursor``: the rollout data cursor read before this batch drew its
    prompts (None: not read). ``sampler`` holds the observation threads of the
    generation; it closes when the batch is joined or abandoned."""

    rollout_id: int
    policy_version: int
    handle: Any
    data_cursor: dict[str, int] | None
    started_at: float
    started_clock: float
    sampler: ExitStack = field(default_factory=ExitStack)
    batch: Any = None

    @property
    def joined(self) -> bool:
        return self.batch is not None


def launch_problems(
    ahead: int,
    *,
    backend_max: int,
    max_policy_age: int,
    placements: Iterable[str],
    sync_supported: bool,
    sample_roles: bool = False,
    elastic: bool = False,
    island_cuts: bool = False,
    overlap_eval: bool = False,
) -> list[str]:
    """What ``--rl-rollout-ahead ahead`` needs and the launch does not have (empty: ok)."""
    if type(ahead) is not int or not 0 <= ahead <= MAX_ROLLOUT_AHEAD:
        return [f"{FLAG} 0..{MAX_ROLLOUT_AHEAD}"]
    if ahead == 0:
        return []
    checks = (
        (ahead > backend_max, f"a backend that generates {ahead} batch ahead "
                              f"(this backend: at most {backend_max})"),
        (max_policy_age < ahead, f"--rl-max-policy-age >= {ahead} (every sample lags {ahead} version)"),
        (any(p != "fixed-partition" for p in placements),
         "--rl-placement fixed-partition (dedicated engine GPUs)"),
        (not sync_supported, "--rl-sync-preset full-parameter with asynchronous rounds, "
                             "or --rl-single-island-no-sync"),
        (sample_roles, "no --rl-sample-role / --rl-island-sample-role (the sample buffer "
                       "has its own policy-age rules)"),
        (elastic, "no --rl-elastic (reconfiguration expects nothing in flight at its safe point)"),
        (island_cuts, "no island round cuts or resume ledger (--rl-cut-every, "
                      "--rl-cut-auto-mtbf-s; --rl-checkpoint-store with --rl-single-island-no-sync)"),
        (overlap_eval, "no --rl-overlap-eval (the engines generate the next batch instead)"),
    )
    return [text for failed, text in checks if failed]


def driver_problems(driver: Any) -> list[str]:
    """What the running island lacks for its ``rollout_ahead`` (empty: ok).

    Checked when the driver starts, on the objects themselves, so a wiring that
    bypassed the launcher still fails closed."""
    ahead = int(getattr(driver, "rollout_ahead", 0) or 0)
    if ahead == 0:
        return []
    if ahead > MAX_ROLLOUT_AHEAD:
        return [f"rollout_ahead {ahead} > {MAX_ROLLOUT_AHEAD}"]
    rollout = driver.rollout
    checks = (
        (not all(callable(getattr(rollout, verb, None)) for verb in ("start_generate", "finish_generate")),
         "the rollout pool has no split generation (start_generate / finish_generate)"),
        (driver._max_policy_age() < ahead, f"max_policy_age >= {ahead}"),
        (driver.colocated, "a fixed-partition island"),
        (bool(getattr(rollout, "offloads_after_generate", False)), "engines that stay resident"),
        (driver.controller is not None, "no reconfiguration controller"),
        (driver.ledger is not None, "no batch ledger (resume store or elastic)"),
        (getattr(driver.sync, "round_cuts", None) is not None, "no island round cuts"),
        (driver.eval_overlap is not None, "no overlapped evaluation"),
    )
    return [text for failed, text in checks if failed]
