"""Sync/train overlap for the full-parameter sweep (S26 E3 item 3, E2 option).

Round k's outer delta is pushed at boundary k and the island trains round
k+1 immediately on its own weights. At boundary k+1 it waits for the global
result of sweep k (``G_k``) and rebases in place::

    theta <- G_k + (theta_local_{k+1} - base_k)

``base_k`` is the cut round k+1 started from. ``G_k`` becomes the anchor, so
the next push ``theta - G_k`` equals round k+1's progress exactly once: round
k's delta is already inside ``G_k`` and is not counted again.

Staleness is configured apart from ``--rl-max-policy-age``. The driver
publishes the boundary's cut to the island's engines before the next
generation (boundary, then publish), so every rollout is still generated by
the weights the trainer then trains: the rollout policy age stays 0 and the
sweep keeps refusing any other value. What overlap adds is a lag of the local
weights behind the global policy of :data:`OUTER_STEP_LAG` outer step (like
one extra DiLoCo local step); it is bound into the role-stream session
contract (``sync_train_overlap``), not into the rollout policy age, which in
Miles would switch on partial rollout (carry-over) or fully_async generation.
"""

from __future__ import annotations

import numpy as np

OUTER_STEP_LAG = 1


def overlap_option_problems(*, max_policy_age: int, fragment_pipeline: int, fragments: int) -> list[str]:
    """Launcher requirements of ``--rl-sync-overlap`` (empty when satisfied).

    * rollout policy age 0: see the module doc (overlap is not rollout staleness);
    * syncer fragment pipeline = P: the syncer then PULLs every fragment of a
      sweep at once, so the island pushes the whole sweep at the boundary. With
      a smaller pipeline the later PULLs arrive while the next round trains and
      wait for the next boundary, which serializes the sweep again."""
    problems = []
    if int(max_policy_age or 0) != 0:
        problems.append("--rl-max-policy-age 0 with --rl-sync-overlap (overlap lags the global "
                        "policy by one outer step; rollouts stay on-policy)")
    if int(fragment_pipeline) != int(fragments):
        problems.append("--rl-sync-fragment-pipeline equal to --fragments with --rl-sync-overlap")
    return problems


def rebase_values(anchor: np.ndarray, current: np.ndarray, base: np.ndarray) -> np.ndarray:
    """``anchor + (current - base)`` in f32 (the trainer keeps its progress)."""
    if not (anchor.shape == current.shape == base.shape):
        raise ValueError("rebase operands have different shapes")
    for name, value in (("anchor", anchor), ("current", current), ("base", base)):
        if value.dtype != np.float32:
            raise ValueError(f"rebase {name} must be float32")
    out = np.subtract(current, base, dtype=np.float32)
    np.add(anchor, out, out=out)
    if not np.isfinite(out).all():
        raise ValueError("rebased fragment has a non-finite value")
    return out
