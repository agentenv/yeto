"""``RolloutPool`` over upstream InferenceController + RolloutExecutor (task 3.2).

``generate`` runs one upstream training rollout (``prepare_rollout`` then
``rollout_executor.get``) and returns a :class:`RolloutBatchHandle` whose
``payload`` is upstream's ``RolloutDataPack`` (object-store refs; never
dereferenced here). The yeto-visible metadata comes from
:mod:`.rollout_meta_hook`, extracted in the rollout process and delivered via
a small sink. ``require_policy_tokens`` implements the pre-training identity
check (spec: mismatching groups are rejected before training).
"""

from __future__ import annotations

