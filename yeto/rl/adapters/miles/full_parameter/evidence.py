"""Per-round trajectory evidence of a full-parameter island.

A full-parameter role stream binds every local round to the exact accepted
batch (:class:`~yeto.rl.trajectory_evidence.TrajectoryBatchEvidence`).  The
rollout process writes that evidence into the island's private directory
before Miles discards the sample metadata; the sync reads it back at the
round boundary (``session.read_round_evidence``).

Runs inside the Miles rollout process.  Import-light: nothing here imports
miles or torch.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from yeto.rl.engine.policy_versions import PublishedPolicies
    from yeto.rl.trajectory_evidence import BehaviorPolicyOf


def evidence_enabled(args: Any) -> bool:
    """Whether this island binds rounds to trajectory evidence (full-parameter)."""

    return getattr(args, "yeto_rl_trajectory_evidence_dir", None) is not None


def persist_published_round_evidence(
    args: Any,
    groups: Sequence[Any],
    policy_token: str | None,
    published: PublishedPolicies,
    *,
    rollout_id: int | None = None,
) -> None:
    """Write one accepted batch, bound to the policy token the driver published
    and every trajectory to the policy that generated it (P0-S, schema 4).

    The caller (the ports rollout hook) calls this only when
    :func:`evidence_enabled`; it is the one writer of round evidence.  The
    driver publishes ``yeto:<rollout_id>:<policy_tensor_hash>`` before each
    rollout (``MilesRolloutPool``); that token is the batch's round and
    policy.  ``published`` maps every version in the policy-age window to
    its weight hash; a trajectory is named by the oldest version on its
    tokens.  The evidence kind comes from the launch context bound on
    ``args``; the context must also bind a schema, but new evidence is
    always schema 4.

    ``rollout_id`` (the round the driver set, ``current_rollout_round``)
    overrides the token's version.  It is higher only under rollout ahead:
    the batch of round r + 1 is generated by version r, so its round policy
    (``behavior_policy_hash``) names the generating policy until the trainer
    binds the round to the policy it trains from
    (``trajectory_evidence.bind_round_policy``).
    """

    from yeto.rl.core import parse_policy_snapshot_token
    from yeto.rl.trajectory_evidence import (
        EVIDENCE_KINDS,
        LAUNCH_CONTEXT_SCHEMA_VERSIONS,
        build_trajectory_batch_evidence,
        write_trajectory_batch_evidence,
    )

    if not policy_token:
        raise RuntimeError("trajectory evidence needs the published policy token")
    evidence_kind = getattr(args, "yeto_rl_trajectory_evidence_kind", None)
    if evidence_kind not in EVIDENCE_KINDS:
        raise RuntimeError("trajectory evidence kind is not bound by the launch context")
    schema_version = getattr(args, "yeto_rl_trajectory_evidence_schema_version", None)
    if schema_version not in LAUNCH_CONTEXT_SCHEMA_VERSIONS:
        raise RuntimeError("trajectory evidence schema is not bound by the launch context")
    token_round, policy_hash = parse_policy_snapshot_token(policy_token)
    if rollout_id is None:
        rollout_id = token_round
    elif rollout_id < token_round:
        raise RuntimeError(f"round {rollout_id} is older than its policy token {policy_token}")
    from ..buffer_rollout import EXTERNAL_CUT_ROUND_ATTR

    external = getattr(args, EXTERNAL_CUT_ROUND_ATTR, None)
    if external is not None:
        # S27 G-EM relay trainer: every trajectory names its external merged cut
        # (schema 5); the age bound is the merged version the round's take gated on.
        from yeto.rl.engine.external_policy import behavior_cut_of

        if int(external["rollout_id"]) != int(rollout_id):
            raise RuntimeError(f"round {rollout_id}: the relay take was for round {external['rollout_id']}")
        evidence = build_trajectory_batch_evidence(
            groups,
            rollout_id=rollout_id,
            behavior_policy_hash=policy_hash,
            reward_contract_hash=getattr(args, "yeto_rl_reward_sha256", None),
            evidence_kind=evidence_kind,
            behavior_cut_of=behavior_cut_of,
            merged_version=int(external["merged_version"]),
            max_policy_age=int(getattr(args, "yeto_rl_max_policy_age", 0) or 0),
        )
        write_trajectory_batch_evidence(args.yeto_rl_trajectory_evidence_dir, evidence)
        return
    evidence = build_trajectory_batch_evidence(
        groups,
        rollout_id=rollout_id,
        behavior_policy_hash=policy_hash,
        reward_contract_hash=getattr(args, "yeto_rl_reward_sha256", None),
        evidence_kind=evidence_kind,
        behavior_policy_of=_oldest_published_policy(published),
        # the configured limit (the driver's age check applies any fallback)
        max_policy_age=int(getattr(args, "yeto_rl_max_policy_age", 0) or 0),
    )
    write_trajectory_batch_evidence(args.yeto_rl_trajectory_evidence_dir, evidence)


def _oldest_published_policy(published: PublishedPolicies) -> BehaviorPolicyOf:
    from ..carry_over import sample_versions

    def behavior_policy(segments: Sequence[Any]) -> tuple[int, str]:
        versions = {v for sample in segments for v in sample_versions(sample)}
        if not versions or None in versions:
            raise RuntimeError("a trained trajectory has tokens of unknown policy version")
        oldest = min(versions)
        policy_hash = published.hash_of(oldest)
        if policy_hash is None:
            raise RuntimeError(f"policy v{oldest} of a trained trajectory was not published")
        return oldest, policy_hash

    return behavior_policy
