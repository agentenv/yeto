    def load_sample(self, *, http_get: Callable[[str], Any] | None = None) -> dict[str, Any] | None:
        """rl-infra-spec 1.7: one load sample for ``timeline.classify_load``.

        * ``active_requests``/``workers``/``cordoned``: fork-M3 router
          ``GET /worker_inflight`` (E1's drain reads ``active_requests``);
        * ``running_requests``/``queued_requests``: sum over engines of SGLang
          ``GET /get_load`` (``num_reqs - num_waiting_reqs`` / ``num_waiting_reqs``);
        * ``engine_capacity``: sum over engines of SGLang ``/server_info``
          ``effective_max_running_requests_per_dp`` (read once per engine);
        * ``tool_wait_trajectories``: the ToolWaitBoard count (0 for stock
          generate, None = unknown);
        * ``load_class``: ``classify_load`` of the above, ``"unknown"`` if any
          input is unknown. ``ready_groups`` is not observable mid-rollout: None.

        None when the router (and its ``/workers`` fallback) is unknown: unknown,
        never reported as 0; a rate-limited warning names the reason. A failing engine endpoint makes its field None.
        """
        get = http_get or _http_get_json
        router = self._router_inflight(get)
        if router is None:
            return None
        inflight = router["inflight"]
        sample: dict[str, Any] = {
            "active_requests": int(sum(int(v) for v in inflight.values())),
            "workers": len(inflight),
            "cordoned": len(router["cordoned"]),
        }
        running: int | None = 0
        queued: int | None = 0
        capacity: int | None = 0
        kv_used: int | None = 0
        kv_capacity: int | None = 0
        for url in sorted(inflight):
            base = url.rstrip("/")
            try:
                entries = get(base + "/get_load")
                load = _engine_load(entries)
            except Exception:  # noqa: BLE001
                entries = load = None
            used = _engine_kv_used(entries)
            kv_used = None if used is None or kv_used is None else kv_used + used
            if load is None:
                running = queued = None
            elif running is not None:
                running += load[0]
                queued += load[1]
            if url not in self._capacity:
                try:
                    info = get(base + "/server_info")
                except Exception:  # noqa: BLE001
                    info = None
                cap = _engine_capacity(info)
                if cap is not None:
                    self._capacity[url] = cap
                kv_cap = _engine_kv_capacity(info)
                if kv_cap is not None:
                    self._kv_capacity[url] = kv_cap
            cap = self._capacity.get(url)
            capacity = None if cap is None or capacity is None else capacity + cap
            kv_cap = self._kv_capacity.get(url)
            kv_capacity = None if kv_cap is None or kv_capacity is None else kv_capacity + kv_cap
        tool = self._tool_wait_count()
        sample.update(
            running_requests=running,
            queued_requests=queued,
            engine_capacity=capacity or None,
            tool_wait_trajectories=tool,
            ready_groups=None,
        )
        # agentic-rollout-utilization 1.3 (only when the engines report them, so
        # older engines' load samples are unchanged)
        if kv_used is not None and inflight:
            sample["kv_used_tokens"] = kv_used
        if kv_capacity and inflight:
            sample["kv_capacity_tokens"] = kv_capacity
        harness = self._harness_snapshot()  # IR-2/IR-4; None = unknown
        sample.update(
            harness_in_flight=None if harness is None else int(harness.in_flight),
            env_live=None if harness is None else int(harness.env_live),
            tito_session_mismatch=None if harness is None else int(harness.tito_session_mismatch),
            tito_chain_breaks=None if harness is None else dict(harness.tito_chain_breaks),
            policy_age_violation=None if harness is None else int(harness.policy_age_violation),
        )
        from yeto.rl.engine.timeline import LoadSample, classify_load

        known = None not in (running, queued, sample["engine_capacity"], tool)
        sample["load_class"] = (
            classify_load(LoadSample(queued_requests=queued, active_requests=running,
                                     tool_wait_trajectories=tool, ready_groups=0,
                                     engine_capacity=sample["engine_capacity"],
                                     harness_in_flight=sample["harness_in_flight"] or 0,
                                     env_live=sample["env_live"] or 0))
            if known else "unknown"
        )
        return sample

