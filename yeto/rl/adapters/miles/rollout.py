class DirMetadataSource:
    """Reads the ``dir:`` sink; the file is consumed (deleted) once read."""

    def __init__(self, directory: str | Path) -> None:
        self.directory = Path(directory)

    @property
    def sink_spec(self) -> str:
        return f"dir:{self.directory}"

    def set_policy_token(self, token: str) -> None:
        put_policy_token(token, self.sink_spec)

    def set_max_policy_age(self, limit: int) -> None:
        put_max_policy_age(limit, self.sink_spec)

    def take(self, rollout_id: int) -> dict[str, Any]:
        for name in (f"rollout-{rollout_id}.json", "rollout-latest.json"):
            path = self.directory / name
            if path.exists():
                payload = json.loads(path.read_text(encoding="utf-8"))
                path.unlink()
                extra = []
                round_path = self.directory / f"round-{rollout_id}.json"
                if round_path.exists():
                    extra.append(json.loads(round_path.read_text(encoding="utf-8")))
                    round_path.unlink()
                return merge_round_metadata(payload, extra, rollout_id)
        raise RolloutMetadataError(f"no rollout metadata for rollout {rollout_id} in {self.directory}")


def merge_round_metadata(
    payload: dict[str, Any], records: list[dict[str, Any]], rollout_id: int
) -> dict[str, Any]:
    """Attach per-round counters reported after the all-samples hook (same rollout only)."""

    merged = dict(payload)
    for record in records:
        if record.get("rollout_id") != rollout_id:
            raise RolloutMetadataError(
                f"per-round metadata for rollout {record.get('rollout_id')} "
                f"arrived with rollout {rollout_id}"
            )
        for key, value in record.items():
            if key in ("schema", "rollout_id"):
                continue
            if key in merged:
                raise RolloutMetadataError(f"per-round metadata {key} reported twice")
            merged[key] = value
    return merged


def _sink_actor_class():
    import ray

    @ray.remote(num_cpus=0)
    class _YetoRolloutMetaSink:
        def __init__(self) -> None:
            self._pending: list[str] = []
            self._token: str | None = None

        def set_token(self, token: str) -> None:
            self._token = token

        def get_token(self) -> str | None:
            return self._token

        # agentic-rollout-utilization 3.5/4.1: the run's policy-age limit after a
        # governor fallback (None = the configured limit; only ever lowered).
        def set_limit(self, limit: int) -> None:
            self._limit = int(limit)

        def get_limit(self) -> int | None:
            return getattr(self, "_limit", None)

        def put(self, encoded: str) -> None:
            self._pending.append(encoded)

        def take_all(self) -> list[str]:
            items, self._pending = self._pending, []
            return items

    return _YetoRolloutMetaSink


class RayMetadataSink:
    """Named Ray actor that rollout-process hooks push metadata into."""

    def __init__(self, name: str = DEFAULT_SINK_ACTOR, *, timeout_s: float = 30.0) -> None:
        import ray

        self.name = name
        self.timeout_s = timeout_s
        self._ray = ray
        self._actor = _sink_actor_class().options(name=name, get_if_exists=True).remote()

    @property
    def sink_spec(self) -> str:
        return f"ray:{self.name}"

    def set_policy_token(self, token: str) -> None:
        self._ray.get(self._actor.set_token.remote(token))

    def set_max_policy_age(self, limit: int) -> None:
        self._ray.get(self._actor.set_limit.remote(int(limit)))

    def take(self, rollout_id: int) -> dict[str, Any]:
        deadline = time.monotonic() + self.timeout_s
        while True:
            items = [json.loads(i) for i in self._ray.get(self._actor.take_all.remote())]
            main = [i for i in items if i.get("schema") != ROUND_META_SCHEMA]
            extra = [i for i in items if i.get("schema") == ROUND_META_SCHEMA]
            if items:
                if len(main) != 1:
                    raise RolloutMetadataError(
                        f"expected one metadata record for rollout {rollout_id}, got {len(main)}"
                    )
                return merge_round_metadata(main[0], extra, rollout_id)
            if time.monotonic() > deadline:
                raise RolloutMetadataError(f"no rollout metadata for rollout {rollout_id}")
            time.sleep(0.05)


