class PolicyTokenMismatch(RuntimeError):
    """Some groups were generated by a policy other than the expected snapshot."""

    def __init__(self, expected: str, groups: tuple[GroupMetadata, ...]) -> None:
        detail = ", ".join(f"{g.group_id}={g.policy_token!r}" for g in groups)
        super().__init__(f"policy token mismatch (expected {expected!r}): {detail}")
        self.expected = expected
        self.groups = groups


