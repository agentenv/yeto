def _engine_load(entries: Any) -> tuple[int, int] | None:
    """SGLang ``/get_load`` (one entry per DP rank) -> (running, waiting)."""
    if not isinstance(entries, list) or not entries:
        return None
    running = waiting = 0
    for entry in entries:
        if not isinstance(entry, dict) or "num_reqs" not in entry or "num_waiting_reqs" not in entry:
            return None
        total, queued = int(entry["num_reqs"]), int(entry["num_waiting_reqs"])
        running += total - queued
        waiting += queued
    return running, waiting


def _engine_kv_used(entries: Any) -> int | None:
    """agentic-rollout-utilization 1.3: KV tokens in use, SGLang ``/get_load``
    (``num_tokens - num_pending_tokens`` = the scheduler's ``num_used_tokens``,
    summed over DP ranks). None when an older engine omits the fields."""
    if not isinstance(entries, list) or not entries:
        return None
    used = 0
    for entry in entries:
        if not isinstance(entry, dict):
            return None
        total, pending = entry.get("num_tokens"), entry.get("num_pending_tokens")
        if type(total) is not int or type(pending) is not int:
            return None
        used += total - pending
    return used


def _engine_kv_capacity(info: Any) -> int | None:
    """SGLang ``/server_info`` ``internal_states[*].memory_usage.token_capacity`` (sum)."""
    if not isinstance(info, dict):
        return None
    states = info.get("internal_states")
    if not isinstance(states, list) or not states:
        return None
    values = [(s.get("memory_usage") or {}).get("token_capacity") if isinstance(s, dict) else None
              for s in states]
    if all(type(v) is int and v > 0 for v in values):
        return int(sum(values))
    return None


def _engine_capacity(info: Any) -> int | None:
    """SGLang ``/server_info``: concurrent requests the engine admits (sum over DP ranks)."""
    if not isinstance(info, dict):
        return None
    states = info.get("internal_states")
    if isinstance(states, list) and states:
        values = [s.get("effective_max_running_requests_per_dp") for s in states
                  if isinstance(s, dict)]
        if values and all(isinstance(v, int) and v > 0 for v in values):
            return int(sum(values))
    value = info.get("max_running_requests")
    return int(value) if isinstance(value, int) and value > 0 else None


class MilesRolloutPool:
    """``RolloutPool`` port. ``expected_policy`` returns the published (version, hash)."""

    def __init__(
        self,
        *,
        inference_controller: Any,
        rollout_executor: Any,
        metadata: MetadataSource,
        expected_policy: Callable[[], tuple[int, str]],
        runner: LoopRunner | None = None,
        args: Any = None,
        declared_cells: Any = None,
        track_timeout_s: float = 600.0,
        tool_wait_board: Any = None,
        worker_manager: Any = None,
        bundles: Any = None,
        gpus_per_engine: int | None = None,
        load_tool_wait: Any = None,
        harness: Any = None,
        side_effect_log: Any = None,
    ) -> None:
        # 3.3 X5 evidence: tool_wait.ToolSideEffectLog (or its path); None = off.
        if side_effect_log is not None and not hasattr(side_effect_log, "record"):
            from yeto.rl.engine.tool_wait import ToolSideEffectLog

            side_effect_log = ToolSideEffectLog(side_effect_log)
        self._side_effects = side_effect_log
        # rl-infra-spec 1.7 ToolWaitBoard (local or actor handle); None = no
        # tool-wait count, so trajectory_load() is unknown (None).
        self._tool_wait_board = tool_wait_board
        # IR-2: harness board (tool_wait.HarnessBoard, local or actor handle),
        # HARNESS_NOT_AGENTIC for islands without a harness (explicit zeros),
        # or None = unknown (fails the drain closed).
