def _number(value: Any) -> float:
    return math.nan if value is None else float(value)


def handle_from_metadata(
    payload: dict[str, Any],
    *,
    rollout_id: int,
    policy_version: int,
    policy_hash: str,
    data_pack: Any,
) -> RolloutBatchHandle:
    if not isinstance(payload, dict) or payload.get("schema") != METADATA_SCHEMA:
        raise RolloutMetadataError(f"malformed rollout metadata: {payload!r:.200}")
    reported = payload.get("rollout_id")
    if reported is not None and reported != rollout_id:
        raise RolloutMetadataError(f"metadata is for rollout {reported}, expected {rollout_id}")
    groups = tuple(
        GroupMetadata(
            group_id=str(g["group_id"]),
            sample_ids=tuple(str(s) for s in g["sample_ids"]),
            policy_token=str(g["policy_token"]),
            reward_mean=_number(g["reward_mean"]),
            reward_std=_number(g["reward_std"]),
            token_count=int(g["token_count"]),
            filtered_samples=(
                int(g["filtered_samples"]) if g.get("filtered_samples") is not None else None
            ),
            # 4.1: version segments of a carried-over group (limit > 0 only)
            policy_versions=(
                tuple(int(v) for v in g["policy_versions"]) if g.get("policy_versions") else None
            ),
        )
        for g in payload["groups"]
    )
    if not groups:
        raise RolloutMetadataError(f"rollout {rollout_id} produced no trained groups")
    indices = getattr(data_pack, "sample_indices", None)
    if indices is not None:
        expected = sorted(int(i) for i in payload.get("trained_sample_indices", ()))
        if sorted(int(i) for i in indices) != expected:
            raise RolloutMetadataError(
                f"rollout {rollout_id}: metadata samples do not match the training batch"
            )
    return RolloutBatchHandle(
        rollout_id=rollout_id,
        policy_version=policy_version,
        policy_hash=policy_hash,
        groups=groups,
        completed=int(payload["completed"]),
        aborted=int(payload["aborted"]),
        payload=data_pack,
        # rollout_meta_hook: trained-group filter drops (terminal). Carried-over
        # leftovers (cut-audit §3): the ports path forbids partial rollout, so the
        # only reuse is the data buffer; a reported empty buffer means 0.
        filtered=int(payload["filtered"]) if "filtered" in payload else None,
        # Limit > 0 (agentic-rollout-utilization 4.1): partial rollout puts the
        # groups not completed back into the buffer; their count is reported.
        carried_over=(int(payload["carried_out_groups"]) if "carried_out_groups" in payload
                      else 0 if payload.get("buffer_length") == 0 else None),
        data_cursor=payload.get("data_cursor"),
        buffer_length=payload.get("buffer_length"),
        submitted_groups=payload.get("submitted_groups"),
        aborted_in_flight_groups=payload.get("aborted_in_flight_groups"),
        aborted_in_flight_trajectories=payload.get("aborted_in_flight_trajectories"),
        aborted_in_flight_tokens=payload.get("aborted_in_flight_tokens"),
        aborted_in_flight_unknown_groups=payload.get("aborted_in_flight_unknown_groups"),
        abort_mechanism=MILES_ABORT_MECHANISM,
        tool_wait_seconds=(
            float(payload["tool_wait_seconds"]) if "tool_wait_seconds" in payload else None
        ),
        nonzero_advantages=(
            int(payload["nonzero_advantages"]) if "nonzero_advantages" in payload else None
        ),
        policy_age_violation=(
            int(payload["policy_age_violation"]) if "policy_age_violation" in payload else None
        ),
        batch_summary=payload.get("batch_summary"),
        batch_summary_by_bucket=payload.get("batch_summary_by_bucket"),
        tito_session_mismatch_records=(
            tuple(payload["tito_session_mismatch_records"])
            if payload.get("tito_session_mismatch_records") else None
        ),
        trajectory_rewards=(
            tuple(payload["trajectory_rewards"]) if payload.get("trajectory_rewards") else None
        ),
        carry_over=_carry_over_fields(payload),
        cross_version_truncated_fraction=(
            float(payload["cross_version_truncated_fraction"])
            if payload.get("cross_version_truncated_fraction") is not None else None
        ),
        over_sampling=over_sampling_fields(payload.get("over_sampling")),
    )


