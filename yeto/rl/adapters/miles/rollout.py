async def running_members(controller: Any) -> frozenset[str]:
    """Rollout members = cells the controller reports ``Running``.

    Shared by ``MilesRolloutPool.members`` and ``MilesPublisher`` so both
    sides of the driver's acknowledgement check use one source.
    """

    statuses = await controller.get_cell_statuses() or {}
    return frozenset(
        member_id(cell_id)
        for cell_id, status in statuses.items()
        if getattr(status, "phase", None) == "Running"
    )


def require_policy_tokens(batch: RolloutBatchHandle, expected_token: str) -> None:
    # A group carrying version segments (limit > 0, 4.1) names its oldest version;
    # the driver checked it against the policy-age window before training.
    bad = tuple(g for g in batch.mismatched_groups(expected_token) if not g.policy_versions)
    if bad:
        raise PolicyTokenMismatch(expected_token, bad)


