"""verl :class:`~yeto.rl.engine.engine_outage.EngineRecoveryPort` (S27 G-EW, VERL-PARITY #16).

A verl island in the separate mode (``separate``, ``--rl-placement fixed-partition``)
trains on its trainer cards and generates on standalone vLLM replicas (verl's
``standalone_server_manager``), which get each policy over verl's NCCL checkpoint
engine (``standalone_checkpoint_manager``). When those replicas die (their node is
reclaimed, or their processes end) the trainer must not stop: the engine-neutral
driver (:mod:`yeto.rl.engine.engine_outage`) waits, asks this port to start the
replicas again, republishes the current policy and generates the lost batch again.

The port only calls what verl already offers:

* ``engines_alive``: every standalone replica's server actor answers (a dead Ray
  actor raises at once; a busy one that does not answer within ``probe_s`` counts
  as alive), and the island's Ray has at least ``nodes`` live GPU nodes;
* ``is_engine_loss``: the error is a dead Ray actor, or the engines are not alive;
* ``abort_generation``: verl's sync replay buffer re-issues the prompts of failed
  requests and keeps waiting (fork ``replay_buffer.sample``), so a generation on
  dead replicas never returns by itself. The port wraps the buffer's metadata sync
  (called once per wait loop) to raise :class:`EnginesLost` after an abort; it also
  asks the live replicas to abort their requests (best effort);
* ``nodes_ready``: the GPU nodes are back and every replica's placement group is
  placed again (Ray reschedules the bundles of a dead node onto a node that joins
  with the same resources);
* ``restore_engines``: the old replicas' actors are killed, new replicas of the same
  class and rank start in the old replicas' placement groups (``init_standalone``
  with the existing resource pool; a new name suffix avoids Ray name clashes), the
  load balancer swaps the server addresses and the checkpoint manager swaps the
  replicas. The trainer workers keep their NCCL checkpoint group between updates
  (verl's ``rebuild_group`` default False), so the port drops that group on them;
  the driver's next publication then builds a new group with the new replicas.

Data: the lost batch's prompts are not read again. The verl data cursor cannot move
back (``data_cursor``); verl's replay buffer replaces the failed prompts with new
ones and keeps the groups that finished before the loss (they were generated by the
same published policy).

:class:`TestEngineKill` (TEST ONLY, ``YETO_VERL_TEST_KILL_ENGINES_AT``) kills the
replicas' processes a few seconds into one generation, in the island's first
process only: the GPU check of this port.

Not verified on GPUs at the time of writing: whether the killed vLLM processes free
their GPU memory before the new replica starts; a node loss (a two-node verl
island needs ``--rl-engine-cluster``, which verl does not run yet, VERL-PARITY #15).
"""

from __future__ import annotations

import os
import threading
import time
from collections.abc import Callable, Mapping
from typing import Any

from yeto.rl.engine.engine_outage import EnginesLost

TEST_KILL_ENV = "YETO_VERL_TEST_KILL_ENGINES_AT"  # TEST ONLY "ROLLOUT_ID[:DELAY_S]"


def _ray():
    import ray

    return ray


def _dead_actor_error(ray_module: Any) -> tuple[type[BaseException], ...]:
    exceptions = getattr(ray_module, "exceptions", None)
    return tuple(cls for cls in (getattr(exceptions, "RayActorError", None),
                                 getattr(exceptions, "ActorDiedError", None),
                                 getattr(exceptions, "ActorUnavailableError", None)) if cls is not None)


class VerlEngineRecovery:
    """The port over one verl separate-mode trainer (module doc). ``run`` runs one
    coroutine to completion (the island's private loop)."""

    def __init__(self, trainer: Any, *, nodes: int = 1, run: Callable[[Any], Any],
                 ray_module: Any = None, probe_s: float = 5.0, emit: Callable[..., Any] | None = None) -> None:
        self.trainer = trainer
        self.nodes = int(nodes)
        self.run = run
        self._ray_module = ray_module
        self.probe_s = float(probe_s)
        self.emit = emit or (lambda event, **fields: None)
        self.restores = 0
        self.aborted = threading.Event()
        self._install_abort_hook()

    # ------------------------------------------------------------------ helpers
    @property
    def ray(self) -> Any:
        return self._ray_module if self._ray_module is not None else _ray()

    @property
    def manager(self) -> Any:
        return self.trainer.standalone_server_manager

    def _replicas(self) -> list:
        return list(self.manager.rollout_replicas)

    def _install_abort_hook(self) -> None:
        buffer = self.trainer.replay_buffer
        inner = buffer._sync_metadata_from_transfer_queue
        if getattr(inner, "_yeto_engine_abort", None) is not None:
            raise RuntimeError("verl engine recovery installed twice on one replay buffer")
        aborted = self.aborted

        def checked(*args: Any, **kwargs: Any) -> Any:
            if aborted.is_set():
                raise EnginesLost("verl rollout replicas lost: generation aborted (engine outage)")
            return inner(*args, **kwargs)

        checked._yeto_engine_abort = self  # type: ignore[attr-defined]
        buffer._sync_metadata_from_transfer_queue = checked

    def _alive_gpu_nodes(self) -> int:
        return sum(1 for node in self.ray.nodes()
                   if node.get("Alive") and float((node.get("Resources") or {}).get("GPU", 0) or 0) > 0)

    def _server_alive(self, server: Any) -> bool:
        ray = self.ray
        ref = server.get_server_address.remote()
        ready, _ = ray.wait([ref], timeout=self.probe_s)
        if not ready:
            return True  # busy, not dead: a failed probe is not a loss
        try:
            ray.get(ref)
        except _dead_actor_error(ray):
            return False
        return True

    # ------------------------------------------------------------------ the port
    def engines_alive(self) -> bool:
        if self._alive_gpu_nodes() < self.nodes:
            return False
        return all(self._server_alive(server) for replica in self._replicas() for server in replica.servers)

    def is_engine_loss(self, error: BaseException) -> bool:
        if isinstance(error, EnginesLost) or isinstance(error, _dead_actor_error(self.ray)):
            return True
        return not self.engines_alive()

    def abort_generation(self) -> None:
        """Called from the outage monitor thread: the island loop (``run``) belongs to
        the driver thread, so the replicas' abort runs on a loop of its own."""
        import asyncio

        self.aborted.set()
        for replica in self._replicas():
            try:
                asyncio.run(asyncio.wait_for(replica.abort_all_requests(reject_request=True), self.probe_s))
            except Exception:  # noqa: BLE001 - a dead replica refuses; the hook above ends the wait
                pass

    def nodes_ready(self) -> bool:
        if self._alive_gpu_nodes() < self.nodes:
            return False
        table = self.ray.util.placement_group_table
        for replica in self._replicas():
            for group in replica.resource_pool.get_placement_groups():
                if str(table(group).get("state", "")).upper() != "CREATED":
                    return False
        return True

    def _kill(self, replicas: list) -> list[str]:
        errors = []
        for replica in replicas:
            for handle in [*replica.servers, *replica.workers]:
                try:
                    self.ray.kill(handle, no_restart=True)
                except Exception as exc:  # noqa: BLE001 - already dead
                    errors.append(f"{type(exc).__name__}: {exc}"[:200])
        return errors

    def _drop_actor_groups(self) -> list:
        """The trainer side keeps its NCCL checkpoint group between updates (verl's
        ``rebuild_group`` default False) and would reuse it with the dead replicas'
        ranks; drop it on every actor worker, so the next update builds a new group
        with the new replicas (s27-ew-o3: the reused group failed its barrier)."""
        workers = self.trainer.actor_rollout_wg.workers
        refs = [worker.__ray_call__.remote(_drop_checkpoint_group) for worker in workers]
        return self.ray.get(refs, timeout=180)

    def restore_engines(self) -> dict[str, Any]:
        manager = self.manager
        checkpoints = self.trainer.standalone_checkpoint_manager
        old = self._replicas()
        self.restores += 1
        kill_errors = self._kill(old)
        dropped = self._drop_actor_groups()
        suffix = f"yeto{self.restores}"
        new = [manager.rollout_replica_class(
            replica_rank=replica.replica_rank, config=manager.rollout_config, model_config=manager.model_config,
            gpus_per_node=manager.rollout_config.n_gpus_per_node, name_suffix=suffix) for replica in old]
        started = time.monotonic()

        async def start() -> None:
            import asyncio

            await asyncio.gather(*[replica.init_standalone(resource_pool=previous.resource_pool)
                                   for replica, previous in zip(new, old, strict=True)])

        self.run(start())
        balancer = manager.global_load_balancer
        self.ray.get(balancer.remove_servers.remote([replica.server_address for replica in old]))
        self.ray.get(balancer.add_servers.remote({replica.server_address: replica.server_handle
                                                  for replica in new}))
        manager.rollout_replicas = new
        manager.server_handles = [replica.server_handle for replica in new]
        manager.server_addresses = [replica.server_address for replica in new]
        checkpoints.remove_replicas(old)
        checkpoints.add_replicas(new)
        self.aborted.clear()
        return {"replicas": [replica.replica_rank for replica in new],
                "addresses": list(manager.server_addresses), "restore": self.restores,
                "start_s": round(time.monotonic() - started, 1), "trainer_groups": dropped,
                **({"kill_errors": kill_errors} if kill_errors else {})}


def _drop_checkpoint_group(worker_dict: Any, collective: Any = None) -> dict[str, Any]:
    """Runs in a trainer (actor) worker: forget the NCCL checkpoint-engine group (Ray
    collective) this worker holds with the lost replicas. Its communicators are
    aborted, not destroyed (a destroy may wait on the dead peers), and rank 0 removes
    the group's rendezvous stores (Ray named actors holding the old NCCL unique id)."""
    from .ports_impl import _inner_worker

    engine = getattr(_inner_worker(worker_dict), "checkpoint_engine", None)
    name = getattr(engine, "group_name", None)
    if not name:
        return {"group": None, "dropped": False}
    if collective is None:
        from ray.util.collective import collective
    if not collective.is_group_initialized(name):
        return {"group": name, "dropped": False}
    with collective._group_mgr_lock:
        group = collective._group_mgr._name_group_map.pop(name)
    comm_map = getattr(group, "_dev_comm_map", None) or {}
    aborted = 0
    for comms in comm_map.values():
        for comm in comms or ():
            try:
                comm.abort()
                aborted += 1
            except Exception:  # noqa: BLE001 - the communicator is forgotten either way
                pass
    stores = 0
    if getattr(group, "rank", None) == 0:
        for key in list(comm_map):
            try:
                group._destroy_store(group._generate_group_key(key))
                stores += 1
            except Exception:  # noqa: BLE001 - already gone
                pass
    return {"group": name, "dropped": True, "aborted": aborted, "stores": stores}


class TestEngineKill:
    """TEST ONLY (VERL-PARITY #16 GPU check): the island's rollout port, which kills
    every standalone replica's processes ``delay_s`` seconds into the generation of
    ``rollout_id``, once, in the island's first process (``YETO_MODAL_INCARNATION``
    unset or 0). The kill ends the vLLM server actor's process tree (its vLLM
    engine processes) from a rollout worker on the same node, then the replica's
    Ray actors, as a node loss would."""

    __test__ = False  # not a pytest class

    def __init__(self, inner: Any, port: VerlEngineRecovery, rollout_id: int, *, delay_s: float = 5.0,
                 emit: Callable[..., Any] | None = None) -> None:
        self.inner, self.port = inner, port
        self.rollout_id, self.delay_s = int(rollout_id), float(delay_s)
        self.emit = emit or (lambda event, **fields: None)
        self.fired = False

    def __getattr__(self, name: str) -> Any:
        return getattr(self.inner, name)

    def _kill(self) -> None:
        ray = self.port.ray
        killed = []
        for replica in self.port._replicas():
            for server in replica.servers:
                try:
                    pid = ray.get(server.__ray_call__.remote(lambda self: os.getpid()), timeout=30)
                    killed += ray.get(replica.workers[0].__ray_call__.remote(_kill_process_tree, int(pid)),
                                      timeout=60)
                except Exception as exc:  # noqa: BLE001 - recorded, the actor kill below still runs
                    killed.append(f"tree kill failed: {type(exc).__name__}: {exc}"[:200])
        errors = self.port._kill(self.port._replicas())
        self.emit("rl_test_engine_kill", rollout_id=self.rollout_id, killed=killed[:50],
                  kill_errors=errors, time_unix=time.time())

    def generate(self, rollout_id: int, **kwargs: Any) -> Any:
        if not self.fired and int(rollout_id) == self.rollout_id:
            self.fired = True
            timer = threading.Timer(self.delay_s, self._kill)
            timer.daemon = True
            timer.start()
        return self.inner.generate(rollout_id, **kwargs)


def _kill_process_tree(worker: Any, pid: int) -> list[str]:
    """Runs in a rollout worker on the replica's node: SIGKILL ``pid`` and its children."""
    import signal

    import psutil

    del worker
    try:
        root = psutil.Process(pid)
    except psutil.NoSuchProcess:
        return []
    procs = [*root.children(recursive=True), root]
    names = []
    for proc in procs:
        try:
            names.append(f"{proc.pid}:{proc.name()}")
            proc.send_signal(signal.SIGKILL)
        except psutil.NoSuchProcess:
            continue
    psutil.wait_procs(procs, timeout=30)
    return names


def test_kill_at(environ: Mapping[str, str]) -> tuple[int, float] | None:
    """``YETO_VERL_TEST_KILL_ENGINES_AT`` as ``(rollout id, delay s)``; None when unset
    or when this is not the island's first process."""
    from yeto.rl.engine.driver import MODAL_INCARNATION_ENV

    raw = environ.get(TEST_KILL_ENV, "")
    if not raw or str(environ.get(MODAL_INCARNATION_ENV, "0") or "0") != "0":
        return None
    rollout, _, delay = raw.partition(":")
    return int(rollout), float(delay or 5.0)


test_kill_at.__test__ = False  # type: ignore[attr-defined]


def arm_verl_engine_outage(driver: Any, trainer: Any, plan: Mapping[str, Any], *, run: Callable[[Any], Any],
                           environ: Mapping[str, str] | None = None, ray_module: Any = None) -> Any:
    """With ``YETO_ISLAND_ENGINE_RECOVERY_S`` (the outage budget, as on a Miles island)
    a verl separate-mode island survives the loss of its rollout replicas. Nothing
    without the budget, or on an island without standalone replicas (colocated: the
    engines share the trainer's cards and die with it)."""
    from yeto.rl.engine.engine_outage import arm_engine_outage, outage_budget_s

    environ = os.environ if environ is None else environ
    budget = outage_budget_s(environ)
    if budget is None:
        return None
    separate = plan.get("separate")
    if not separate:
        raise ValueError("verl engine recovery needs the separate mode (--rl-placement fixed-partition): "
                         "a colocated island's engines share the trainer's cards")
    nodes = max(int(separate.get("trainer_nodes", 1)), int(separate.get("rollout_nodes", 1)))
    port = VerlEngineRecovery(trainer, nodes=nodes, run=run, ray_module=ray_module, emit=driver.emit)
    outage = arm_engine_outage(driver, port, budget_s=budget, nodes=nodes, backend="verl")
    kill = test_kill_at(environ)
    if kill is not None:
        driver.rollout = TestEngineKill(driver.rollout, port, kill[0], delay_s=kill[1], emit=driver.emit)
    return outage
